print("Sistema Computacional para el Control Energético y Mantenimiento Preventivo de Maquinaria.")


LINEA = "=" * 52
SEPARADOR = "-" * 52
PORCENTAJE_SOBRECONSUMO = 0.15


def leer_texto(mensaje):
    """Pide un texto y repite la pregunta mientras esté vacío."""
    texto = input(mensaje).strip()
    while texto == "":
        print("  [!] Este campo no puede estar vacío.")
        texto = input(mensaje).strip()
    return texto


def leer_real(mensaje, permitir_cero=False):
    """Pide un número real y repite la pregunta mientras sea inválido."""
    while True:
        try:
            valor = float(input(mensaje).replace(",", "."))
        except ValueError:
            print("  [!] Debe ingresar un número válido.")
            continue

        if valor < 0 or (valor == 0 and not permitir_cero):
            print("  [!] El valor debe ser mayor que cero.")
        else:
            return valor


def capturar_datos():
    """Lee todas las entradas de una máquina."""
    print("\n" + LINEA)
    print(" REGISTRO DE UNA MÁQUINA")
    print(LINEA)

    maquina = {
        "id_equipo": leer_texto("Ingrese el ID o código de la máquina: "),
        "tipo_maquina": leer_texto(
            "Ingrese el tipo de máquina (Ej: Motor, Compresor, Excavadora): "
        ),
        "horas_trabajo": leer_real("Ingrese las horas de trabajo acumuladas (hrs): "),
        "consumo_energia": leer_real(
            "Ingrese el consumo total registrado (kWh o Galones): ", permitir_cero=True
        ),
        "costo_unidad_energia": leer_real(
            "Ingrese el costo por unidad de energía ($/kWh o $/Galón): ",
            permitir_cero=True,
        ),
        "limite_horas_mantenimiento": leer_real(
            "Ingrese el límite máximo de horas para mantenimiento preventivo: "
        ),
        "consumo_estandar_hora": leer_real(
            "Ingrese el consumo estándar esperado por hora (según fabricante): ",
            permitir_cero=True,
        ),
    }
    return maquina

def evaluar_maquina(m):
    """Calcula costos y consumos, y decide el diagnóstico de mantenimiento."""
    m["costo_total"] = m["consumo_energia"] * m["costo_unidad_energia"]
    m["costo_por_hora"] = m["costo_total"] / m["horas_trabajo"]
    m["consumo_promedio_hora"] = m["consumo_energia"] / m["horas_trabajo"]
    m["sobreconsumo"] = m["consumo_promedio_hora"] - m["consumo_estandar_hora"]

    if m["sobreconsumo"] > 0:
        m["estado_energetico"] = "ALERTA DE INEFICIENCIA"
    else:
        m["estado_energetico"] = "ÓPTIMO"

    limite_sobreconsumo = m["consumo_estandar_hora"] * PORCENTAJE_SOBRECONSUMO
    exceso_horas = m["horas_trabajo"] >= m["limite_horas_mantenimiento"]
    exceso_consumo = m["sobreconsumo"] > limite_sobreconsumo

    if exceso_horas and exceso_consumo:
        m["estado_mantenimiento"] = "REQUIERE MANTENIMIENTO URGENTE"
        m["motivo"] = "Exceso de horas acumuladas y sobreconsumo crítico."
    elif exceso_horas:
        m["estado_mantenimiento"] = "REQUIERE MANTENIMIENTO URGENTE"
        m["motivo"] = "Exceso de horas acumuladas."
    elif exceso_consumo:
        m["estado_mantenimiento"] = "REQUIERE MANTENIMIENTO URGENTE"
        m["motivo"] = "Sobreconsumo crítico (más del 15 % sobre el estándar)."
    else:
        m["estado_mantenimiento"] = "EN REGLA"
        m["motivo"] = "El equipo no requiere mantenimiento por el momento."

    if exceso_horas:
        m["horas_faltantes"] = 0.0
    else:
        m["horas_faltantes"] = m["limite_horas_mantenimiento"] - m["horas_trabajo"]

    return m

def mostrar_informe(m):
    """Informe de resultados de una sola máquina."""
    print("\n" + LINEA)
    print("              INFORME DE RESULTADOS")
    print(LINEA)
    print(f"Máquina evaluada: {m['id_equipo']} ({m['tipo_maquina']})")
    print(f"Horas acumuladas: {m['horas_trabajo']:,.2f} hrs")

    print(SEPARADOR)
    print(" ANÁLISIS ECONÓMICO:")
    print(f" - Costo total de operación: ${m['costo_total']:,.2f}")
    print(f" - Costo operativo por hora: ${m['costo_por_hora']:,.2f}")

    print(SEPARADOR)
    print(" DESEMPEÑO ENERGÉTICO:")
    print(f" - Consumo promedio por hora: {m['consumo_promedio_hora']:,.4f}")
    print(f" - Consumo estándar esperado: {m['consumo_estandar_hora']:,.4f}")
    print(f" - Estado energético: [{m['estado_energetico']}]")
    if m["sobreconsumo"] > 0:
        print(f"   El equipo presenta un sobreconsumo de {m['sobreconsumo']:,.4f} por hora.")
    else:
        print("   El consumo está dentro del rango esperado.")

    print(SEPARADOR)
    print(" DIAGNÓSTICO DE MANTENIMIENTO PREVENTIVO:")
    print(f" - Estado: [{m['estado_mantenimiento']}]")
    print(f"   {m['motivo']}")

    print(SEPARADOR)
    print(" PRÓXIMO MANTENIMIENTO:")
    if m["horas_faltantes"] == 0:
        print(" - El mantenimiento está pendiente.")
        print(" - Se recomienda realizarlo inmediatamente.")
    else:
        print(f" - Faltan aproximadamente {m['horas_faltantes']:,.2f} horas de trabajo.")
        print(
            " - Se recomienda realizar el mantenimiento al llegar a "
            f"{m['limite_horas_mantenimiento']:,.2f} horas."
        )
    print(LINEA)


def mostrar_resumen(flota):
    """Tabla resumen de todas las máquinas registradas (ciclo for)."""
    if len(flota) == 0:
        print("\n[!] Aún no hay máquinas registradas.")
        return

    print("\n" + LINEA)
    print("        RESUMEN DE MÁQUINAS REGISTRADAS")
    print(LINEA)
    print(f"{'N°':<4}{'ID':<12}{'Tipo':<14}{'Costo/hora':>12}  Estado")
    print(SEPARADOR)

    for i, m in enumerate(flota, start=1):
        print(
            f"{i:<4}{m['id_equipo']:<12}{m['tipo_maquina']:<14}"
            f"${m['costo_por_hora']:>10,.2f}  {m['estado_mantenimiento']}"
        )
    print(LINEA)


def mostrar_comparacion(flota):
    """Compara las máquinas registradas: costo por hora y alertas (ciclo for)."""
    if len(flota) < 2:
        print("\n[!] Registre al menos 2 máquinas para poder compararlas.")
        return

    mas_cara = flota[0]
    mas_barata = flota[0]
    urgentes = 0
    total_costos = 0.0

    for m in flota:
        total_costos += m["costo_total"]
        if m["costo_por_hora"] > mas_cara["costo_por_hora"]:
            mas_cara = m
        if m["costo_por_hora"] < mas_barata["costo_por_hora"]:
            mas_barata = m
        if m["estado_mantenimiento"] != "EN REGLA":
            urgentes += 1

    print("\n" + LINEA)
    print("          COMPARACIÓN ENTRE MÁQUINAS")
    print(LINEA)
    print(f"Máquinas evaluadas: {len(flota)}")
    print(f"Costo total acumulado de la flota: ${total_costos:,.2f}")
    print(
        f"Más costosa por hora: {mas_cara['id_equipo']} ({mas_cara['tipo_maquina']}) "
        f"- ${mas_cara['costo_por_hora']:,.2f}/h"
    )
    print(
        f"Más económica por hora: {mas_barata['id_equipo']} ({mas_barata['tipo_maquina']}) "
        f"- ${mas_barata['costo_por_hora']:,.2f}/h"
    )
    print(f"Máquinas que requieren mantenimiento: {urgentes} de {len(flota)}")
    print(LINEA)

def mostrar_menu():
    print("\n" + LINEA)
    print(" SISTEMA DE EVALUACIÓN ENERGÉTICA Y MANTENIMIENTO")
    print(LINEA)
    print(" 1. Registrar y evaluar una máquina")
    print(" 2. Ver resumen de máquinas registradas")
    print(" 3. Comparar máquinas")
    print(" 4. Salir")


def main():
    flota = []
    opcion = ""

    while opcion != "4":
        mostrar_menu()
        opcion = input("Seleccione una opción: ").strip()

        if opcion == "1":
            maquina = evaluar_maquina(capturar_datos())
            flota.append(maquina)
            mostrar_informe(maquina)
        elif opcion == "2":
            mostrar_resumen(flota)
        elif opcion == "3":
            mostrar_comparacion(flota)
        elif opcion == "4":
            print("\n*** Ejecución finalizada. ***")
        else:
            print("\n[!] Opción no válida. Elija un número del 1 al 4.")


if __name__ == "__main__":
    main()

